-- One row per game per analysed player. The opponent's real username stops at
-- silver: from here on only the hashed opponent_key is used.
select
    username,
    game_uuid,
    url,
    end_time,
    cast(timezone('UTC', end_time) as date) as end_date,
    hour(timezone('UTC', end_time)) as end_hour_utc,
    time_class,
    time_control,
    base_seconds,
    increment_seconds,
    rated,
    player_colour,
    player_rating,
    opponent_key,
    opponent_rating,
    player_rating - opponent_rating as rating_diff,
    player_result,
    outcome,
    case outcome when 'win' then 1.0 when 'draw' then 0.5 else 0.0 end as score,
    end_reason,
    eco_code,
    coalesce(opening_name, 'Unknown') as opening_name,
    coalesce(opening_family, 'Unknown') as opening_family,
    player_accuracy,
    opponent_accuracy,
    plies,
    cast(ceil(plies / 2) as integer) as full_moves
from {{ source('silver', 'silver_games') }}
